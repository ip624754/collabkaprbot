#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Keep in sync with migrations/run.js
const MIGRATION_FILE_RE = /^\d{3}_.+\.sql$/i;

function sha256Hex(s) {
  return crypto
    .createHash('sha256')
    .update(String(s || ''), 'utf8')
    .digest('hex');
}

function escapeSqlLiteral(s) {
  return String(s || '').replace(/'/g, "''");
}

function parseArgs(argv) {
  const args = { dryRun: false, out: null, quiet: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--dry-run') args.dryRun = true;
    else if (a === '--quiet') args.quiet = true;
    else if (a === '--out') {
      args.out = argv[i + 1];
      i++;
    }
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));

  const repoRoot = path.resolve(__dirname, '..');
  const migrationsDir = path.join(repoRoot, 'migrations');
  const outPath = args.out
    ? path.resolve(process.cwd(), args.out)
    : path.join(repoRoot, 'migration_pack', '00_mark_all_applied.sql');

  // Safety: never allow writing the generated pack into migrations/
  const migrationsDirResolved = path.resolve(migrationsDir);
  const outResolved = path.resolve(outPath);
  if (
    outResolved === migrationsDirResolved ||
    outResolved.startsWith(migrationsDirResolved + path.sep)
  ) {
    console.error(
      `[gen-mark-all-applied] Refusing to write into migrations/: ${outResolved}`
    );
    process.exit(1);
  }

  if (!fs.existsSync(migrationsDir)) {
    console.error(`[gen-mark-all-applied] migrations/ not found at: ${migrationsDir}`);
    process.exit(1);
  }

  const dirEntries = fs.readdirSync(migrationsDir);

  // Fail fast if any `.sql` file does NOT match the strict migration naming rule.
  // Prevents accidental inclusion of `00_mark_all_applied.sql` etc.
  const rogueSql = dirEntries
    .filter((f) => String(f).toLowerCase().endsWith('.sql'))
    .filter((f) => !MIGRATION_FILE_RE.test(f))
    .sort();

  if (rogueSql.length) {
    console.error(
      `[gen-mark-all-applied] Unsafe .sql files detected in migrations/ (refusing to run).\n` +
        `Allowed pattern: NNN_name.sql (e.g. 041_example.sql).\n` +
        `Move these files out of migrations/ (usually to migration_pack/):\n` +
        rogueSql.map((x) => `- ${x}`).join('\n')
    );
    process.exit(1);
  }

  const files = dirEntries.filter((f) => MIGRATION_FILE_RE.test(f)).sort();

  if (!files.length) {
    console.error('[gen-mark-all-applied] No migration files found matching /^\\d{3}_.+\\.sql$/');
    process.exit(1);
  }

  const lines = [];
  lines.push('-- Collabka migration pack: mark all current migrations as applied');
  lines.push('-- Auto-generated by: node scripts/gen-mark-all-applied.js');
  lines.push('-- Use ONLY if your DB schema is already up-to-date (e.g. you ran migrations manually before,');
  lines.push('-- or you restored a full DB dump/restore from an already-up-to-date database).');
  lines.push('-- Safe to re-run (idempotent).');
  lines.push('');
  lines.push('CREATE TABLE IF NOT EXISTS schema_migrations (');
  lines.push('  id BIGSERIAL PRIMARY KEY,');
  lines.push('  name TEXT NOT NULL UNIQUE,');
  lines.push('  checksum TEXT NOT NULL,');
  lines.push('  applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()');
  lines.push(');');
  lines.push('');

  for (const f of files) {
    const fullPath = path.join(migrationsDir, f);
    const sql = fs.readFileSync(fullPath, 'utf8');
    const checksum = sha256Hex(sql);
    lines.push(
      `INSERT INTO schema_migrations(name, checksum) VALUES ('${escapeSqlLiteral(
        f
      )}', '${escapeSqlLiteral(checksum)}') ON CONFLICT (name) DO NOTHING;`
    );
  }

  const output = lines.join('\n') + '\n';

  if (args.dryRun) {
    process.stdout.write(output);
    return;
  }

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, output, 'utf8');

  if (!args.quiet) {
    console.log(`[gen-mark-all-applied] Wrote ${files.length} rows to: ${outPath}`);
  }
}

main();
